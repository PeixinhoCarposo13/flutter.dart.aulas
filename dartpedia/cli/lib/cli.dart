// Eu a mantenho para praticar como chamar uma função e conferir seu resultado
// em um teste. O programa de bin/cli.dart não chama esta função.

// calculate não precisa receber dados, por isso os parênteses ficam vazios.
// O int antes do nome indica que ela devolve um número inteiro.
int calculate() {
  // * faz a multiplicação. return entrega o resultado, 42, para quem chamou
  // a função e encerra sua execução; ele não imprime esse valor no terminal.
  return 6 * 7;
}
